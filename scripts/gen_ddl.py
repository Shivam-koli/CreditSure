"""Generate sql/02_tables.sql (raw landing tables + typed cleansed tables) from the actual column sets,
so the DDL can never drift from the code.   python scripts/gen_ddl.py"""
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from lia import config  # noqa: E402

INT_COLS = {"city_tier", "age", "existing_loans_count", "existing_emi_inr", "past_delinquency_24m", "tenure_months",
            "emi_inr", "cibil_new_to_credit", "credit_history_flag", "default_flag", "dependents", "children",
            "policy_term_years", "premium_paying_term_years", "target_invalid", "days_past_due_current"}
BIGINT_COLS = {c for c in ["monthly_income_inr", "co_applicant_income_inr", "loan_amount_inr", "residential_assets_inr",
                           "commercial_assets_inr", "luxury_assets_inr", "bank_assets_inr", "collateral_value_inr",
                           "recovery_amount_inr", "annual_income_inr", "sum_assured_inr", "annual_premium_inr",
                           "modal_premium_inr", "agent_commission_inr", "cibil_score"]}
TABLES = [  # (raw csv, raw table, clean parquet, clean table, pk)
    ("loan_applications_raw.csv", "raw_loan_applications", "loan_clean.parquet", "loan_clean", "application_id"),
    ("loan_new_applications_raw.csv", "raw_loan_new", "loan_new_clean.parquet", "loan_new_clean", "application_id"),
    ("insurance_policies_raw.csv", "raw_insurance_policies", "insurance_clean.parquet", "insurance_clean", "policy_id"),
    ("insurance_new_policies_raw.csv", "raw_insurance_new", "insurance_new_clean.parquet", "insurance_new_clean", "policy_id"),
]


def col_type(name, dtype):
    if name == "application_date":
        return "DATE NOT NULL"
    if name in INT_COLS:
        return "INT"
    if name in BIGINT_COLS:
        return "DOUBLE"
    if pd.api.types.is_float_dtype(dtype) or pd.api.types.is_integer_dtype(dtype):
        return "DOUBLE"
    return "VARCHAR(48)"


out = ["-- GENERATED by scripts/gen_ddl.py -- raw landing tables (everything as text, duplicates allowed)",
       "-- and typed cleansed tables (one row per application / policy).", ""]
for csv, raw, pq, clean, pk in TABLES:
    cols = pd.read_csv(config.DATA_RAW / csv, nrows=0).columns
    out.append(f"DROP TABLE IF EXISTS {raw};")
    out.append(f"CREATE TABLE {raw} (\n  " + ",\n  ".join(f"{c} {'VARCHAR(24)' if c in (pk, 'customer_id') else 'VARCHAR(64)'}" for c in cols) + "\n);")
    out.append(f"CREATE INDEX idx_{raw}_id ON {raw} ({pk});\n")
    df = pd.read_parquet(config.DATA_PROCESSED / pq)
    out.append(f"DROP TABLE IF EXISTS {clean};")
    defs = []
    for c in df.columns:
        t = f"VARCHAR(24) NOT NULL PRIMARY KEY" if c == pk else col_type(c, df[c].dtype)
        defs.append(f"{c} {t}")
    out.append(f"CREATE TABLE {clean} (\n  " + ",\n  ".join(defs) + "\n);")
    out.append(f"CREATE INDEX idx_{clean}_date ON {clean} (application_date);\n")
(ROOT / "sql" / "02_tables.sql").write_text("\n".join(out))
print("wrote sql/02_tables.sql", len(out), "statements")
